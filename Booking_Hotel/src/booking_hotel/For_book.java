    private void btn_SubmitActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btn_SubmitActionPerformed
        // TODO add your handling code here:
        String selectedRoom = (String) cbmx_room.getSelectedItem();
        String Name = txt_name.getText();
        String Phone = txt_phone.getText();
        String RoomType = getRoomType(selectedRoom);
        String Price = getPrice(selectedRoom);
        selectedRoom = (String) cbmx_room.getSelectedItem();

        try {
            FileWriter Writer = new FileWriter("src/Booking_Hotel/Booking_Person.txt", true);
            Writer.write(selectedRoom + "," + RoomType + "," + Price + "," + Name + "," + Phone);
            Writer.close();
            JOptionPane.showMessageDialog(this, "Room Type: " + getRoomType(selectedRoom));
            JOptionPane.showMessageDialog(this, "Booking successful. >w<");

            cbmx_room.removeItem(selectedRoom);

            Manage_Room manageRoom = new Manage_Room();
            manageRoom.setVisible(true);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Error. ", "Error", JOptionPane.ERROR_MESSAGE);
        }

    }//GEN-LAST:event_btn_SubmitActionPerformed

