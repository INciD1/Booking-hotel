    public void setSelectedRoom(String room) {
        selectedRoom = room;
        cbmx_room.setSelectedItem(room);
    }

    private String getRoomType(String selectedRoom) {
        switch (selectedRoom) {
            case "101":
                return "Standard";
            case "102":
                return "Deluxe";
            case "103":
                return "Premium";
            case "104":
                return "Superior";
            case "105":
                return "Super Earth";
            default:
                return " ";
        }
    }

    private String getPrice(String selectedRoom) {
        switch (selectedRoom) {
            case "101":
                return "3000";
            case "102":
                return "4500";
            case "103":
                return "6000";
            case "104":
                return "7500";
            case "105":
                return "9500";
            default:
                return " ";
        }
    }
