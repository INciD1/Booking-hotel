    private void addBookingToTable(String roomNo, String name, String phone) {
        dtm = (DefaultTableModel) table_show_manage.getModel();
        for (int row = 0; row < dtm.getRowCount(); row++) {
            if (dtm.getValueAt(row, 0).equals(roomNo)) {
                dtm.setValueAt("Booked", row, 5);
                return;
            }
        }
    }

