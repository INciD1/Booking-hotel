    private void readFileTableModel() {
         File file = new File("src/booking_hotel/Booking_Person.txt");

    try {
        DefaultTableModel model = (DefaultTableModel) table_show_manage.getModel();

        Scanner scanner = new Scanner(file);
        while (scanner.hasNextLine()) {
            String[] parts = scanner.nextLine().split(",");
            String roomNo = parts[0];
            String type = parts[1];
            String price = parts[2];
            String name = parts[3];
            String phone = parts[4];
            boolean isBooked = true;


            for (int row = 0; row < model.getRowCount(); row++) {
                if (model.getValueAt(row, 0).equals(roomNo)) {
                    isBooked = false;
                    break;
                }
            }


            if (isBooked) {
                model.addRow(new Object[]{roomNo, type, price, name, phone, "Booked"});
            }
        }

        scanner.close();
    } catch (Exception e) {
        JOptionPane.showMessageDialog(this, "File not found: " + e.getMessage(), "Error", JOptionPane.ERROR_MESSAGE);
    }
}

